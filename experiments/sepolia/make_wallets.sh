#!/usr/bin/env bash
# Generates THREE dedicated Sepolia TEST wallets (client, provider, verifier) as encrypted keystores plus
# password files, owner-only, OUTSIDE the repository. Run it yourself, in a terminal:
#
#     bash experiments/sepolia/make_wallets.sh
#
# * You type each password twice, hidden (min 12 characters). It goes to a 0600 password file and to
#   `cast wallet new` through a pipe: never into a command line, a variable that is exported, a log or Git.
# * It refuses to overwrite an existing wallet, to use a directory inside the repository, or to continue
#   without a terminal. It prints only the three addresses.
# * The keys are random, generated by Foundry on this machine. NEVER import a key you use anywhere else.
set -euo pipefail
umask 077
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd -P)"
DIR="${SETTLANE_TESTNET_DIR:-$HOME/.settlane-sepolia}"
export PATH="$HOME/tools/foundry/bin:$PATH"
die() { echo "make_wallets: $*" >&2; exit 1; }

command -v cast >/dev/null   || die "cast not found: run bash experiments/anvil/install_foundry.sh"
command -v script >/dev/null || die "script(1) not found (util-linux): needed to answer cast's password prompt without putting the password in a command line"
[ -t 0 ] || die "no terminal: run this in an interactive shell"
# Keep terminal echo OFF for the whole run (not only during each prompt): type-ahead typed while a keystore is
# being generated would otherwise be echoed to the screen and its scrollback. Restored on exit.
SAVED_STTY="$(stty -g)"; trap 'stty "$SAVED_STTY" 2>/dev/null || true' EXIT; stty -echo
REAL="$(realpath -m "$DIR")"
case "$REAL" in "$REPO"|"$REPO"/*) die "$DIR is inside the repository: secrets never live in the checkout";; esac
for role in client provider verifier; do
  [ -e "$DIR/keystores/$role" ] || [ -e "$DIR/passwords/$role.pw" ] && die "the $role wallet already exists in $DIR: refusing to overwrite (move or delete it yourself)"
done
mkdir -p "$DIR/keystores" "$DIR/passwords"
chmod 700 "$DIR" "$DIR/keystores" "$DIR/passwords"

for role in client provider verifier; do
  read -rsp "Password for the $role wallet (min 12 characters, not shown): " p1; echo
  read -rsp "Same password again: " p2; echo
  [ "$p1" = "$p2" ] || die "the two passwords differ: nothing was created for $role"
  [ "${#p1}" -ge 12 ] || die "the password is shorter than 12 characters"
  printf %s "$p1" > "$DIR/passwords/$role.pw"
  chmod 600 "$DIR/passwords/$role.pw"
  printf '%s\n%s\n' "$p1" "$p1" | script -qec "cast wallet new '$DIR/keystores' '$role'" /dev/null >/dev/null 2>&1 || true
  unset p1 p2
  [ -f "$DIR/keystores/$role" ] || die "cast did not create the $role keystore"
  chmod 600 "$DIR/keystores/$role"
done

echo
python3 "$HERE/testnet.py" check-wallets
echo
echo "Back up $DIR/keystores and $DIR/passwords somewhere private if you want to keep these wallets. They hold test ETH only."
