#!/usr/bin/env node
// Generates src/contract/abi.ts from the production build's ABI (out/Settlane.abi.json, produced by
// `rm -rf out && fe build` at the repository root), and cross-checks it against the ABI lock in
// scripts/lint-policy.json (the same lock the Fe policy lint enforces on the build).
//
//   node scripts/sync-abi.mjs           write src/contract/abi.ts
//   node scripts/sync-abi.mjs --check   fail if src/contract/abi.ts differs from a fresh generation
//
// The contract and its ABI are frozen; this script never changes them, it only mirrors them.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const built = path.join(repo, "out/Settlane.abi.json");
const lockFile = path.join(repo, "scripts/lint-policy.json");
const target = path.join(here, "../src/contract/abi.ts");
const check = process.argv.includes("--check");

const fail = (msg) => {
  console.error(`sync-abi: ${msg}`);
  process.exit(1);
};

if (!existsSync(built)) fail(`${path.relative(repo, built)} is missing: run \`rm -rf out && fe build\` at the repository root first`);
const abi = JSON.parse(readFileSync(built, "utf8"));

// Cross-check against the lock: "name(inputs)->(outputs)" -> stateMutability, exactly.
const sig = (x) => `${x.name}(${x.inputs.map((i) => i.type).join(",")})->(${(x.outputs ?? []).map((o) => o.type).join(",")})`;
const fns = Object.fromEntries(abi.filter((x) => x.type === "function").map((x) => [sig(x), x.stateMutability]));
const lock = JSON.parse(readFileSync(lockFile, "utf8")).contracts.Settlane.abi.functions;
const a = JSON.stringify(Object.entries(fns).sort());
const b = JSON.stringify(Object.entries(lock).sort());
if (a !== b) fail(`the built ABI's functions differ from the lock in scripts/lint-policy.json\n built: ${a}\n lock:  ${b}`);

const body =
  "// GENERATED by frontend/scripts/sync-abi.mjs from out/Settlane.abi.json (`fe build`, Fe 26.6.0).\n" +
  "// Do not edit: run `npm run sync-abi`. `npm run check-abi` (CI job `frontend`) fails on any drift.\n" +
  `export const settlaneAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

if (check) {
  if (!existsSync(target)) fail("src/contract/abi.ts is missing: run `npm run sync-abi`");
  if (readFileSync(target, "utf8") !== body) fail("src/contract/abi.ts differs from the production build's ABI: run `npm run sync-abi` and review the diff");
  console.log(`sync-abi: ok (${abi.filter((x) => x.type === "function").length} functions, ${abi.filter((x) => x.type === "event").length} events, equal to the build and the lock)`);
} else {
  writeFileSync(target, body);
  console.log(`sync-abi: wrote ${path.relative(repo, target)}`);
}
